def get_help_text(page_key, lang="ru"):
    """Получить текст инструкции для страницы."""
    if page_key not in HELP_GUIDE:
        page_key = "dashboard"  # По умолчанию
    
    guide = HELP_GUIDE[page_key]
    
    # Если есть перевод на нужный язык, используем его
    if lang in guide:
        return guide[lang]
    
    # Иначе используем русский как fallback
    return guide.get("ru", {
        "title": "ℹ️ Инструкция",
        "content": "Инструкция для этого раздела пока не доступна."
    })