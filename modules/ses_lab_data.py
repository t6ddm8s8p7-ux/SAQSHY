def find_lab_categories(text):
    """Возвращает категории лабораторных исследований, подходящие к тексту объекта."""
    text_l = str(text or "").lower()
    found = []
    for cat in LAB_CATEGORIES:
        if any(k in text_l for k in cat["keywords"]):
            found.append(cat)
    return found