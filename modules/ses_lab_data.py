def find_lab_categories(item_text):
    """Возвращает категории лабораторных исследований, подходящие к тексту объекта.
    Ключ 'not' — слова-исключения: если такое слово есть в тексте, категория НЕ показывается."""
    t = (item_text or "").lower()
    result = []
    for cat in CATEGORIES:
        if any(k.lower() in t for k in cat.get("not", [])):
            continue
        if any(k.lower() in t for k in cat["keys"]):
            result.append({
                "title": cat["title"],
                "sanepid": [],
                "prodcontrol": cat["pc"],
            })
    return result